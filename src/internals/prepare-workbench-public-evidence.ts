import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import {
  preparePackagedPublicBaselineEvidenceV1,
  resolveOperationalAdminBaselineEvidenceV1,
} from "../org-policy/admin-baseline-evidence-operations-v1.js";
import { defaultPreparedWorkbenchCatalog } from "../org-policy/workbench/prepared-catalog.js";

// Internal release preparation. This is not an AIH target command or browser API.
// The existing administrator bootstrap supplies artifact/attestation locations;
// actual production gh verification must succeed before a module can be emitted.
const args = process.argv.slice(2);
if (
  args.length !== 4 ||
  args[0] !== "--admin-root" ||
  !args[1] ||
  args[2] !== "--output" ||
  !args[3]
)
  throw new TypeError(
    "Usage: prepare-workbench-public-evidence --admin-root <preparation-root> --output <new-module.ts>",
  );
const now = `${new Date().toISOString().slice(0, 19)}Z`;
const resolved = await resolveOperationalAdminBaselineEvidenceV1({
  adminRoot: resolve(args[1]),
  posture: "vibe",
  now,
});
const prepared = preparePackagedPublicBaselineEvidenceV1(
  resolved,
  defaultPreparedWorkbenchCatalog().bundle,
  now,
);
const source = [
  "// Generated by actual Core release evidence preparation. Review both literals together.",
  `export const PACKAGED_PUBLIC_BASELINE_BYTES_V1: string | null = ${JSON.stringify(prepared.bytes)};`,
  `export const PACKAGED_PUBLIC_BASELINE_SHA256_V1: string | null = ${JSON.stringify(prepared.sha256)};`,
  "",
].join("\n");
writeFileSync(resolve(args[3]), source, { encoding: "utf8", flag: "wx", mode: 0o600 });
console.log(
  `Prepared public evidence module ${prepared.sha256}. No publication or signing was performed.`,
);
